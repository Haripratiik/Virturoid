    def test_mvp_builds_robot_arm_and_training_scene_set(self):
        project = build_mvp_robot_arm_project()

        self.assertEqual("fixed_arm.three_dof.tabletop", project["robot_genome"].species)
        self.assertGreaterEqual(len(project["selected_components"]), 4)
        self.assertGreaterEqual(len(project["cad_models"]), 5)
        self.assertEqual("pick_place_sort", project["task_graph"].task_type)
        self.assertEqual(2, len(project["baseline_scene_set"].scenes))
        self.assertEqual(10, len(project["scene_set"].scenes))
        self.assertEqual("variation", project["scene_set"].purpose)
        self.assertEqual(3, len(project["edge_case_scene_set"].scenes))       # activated edge_case difficulty
        self.assertEqual("edge_case", project["edge_case_scene_set"].purpose)
        self.assertGreaterEqual(len(project["regression_scene_set"].scenes), 1)
        self.assertEqual("regression", project["regression_scene_set"].purpose)
        self.assertEqual(3, len(project["holdout_scene_set"].scenes))
        self.assertGreaterEqual(project["training_manifest"].total_scene_count, 20)   # the plan's >=20 bar
        self.assertEqual(
            {"baseline", "variation", "edge_case", "regression", "holdout"},
            {group.purpose for group in project["training_manifest"].scene_groups},
        )


    def test_mvp_produces_failure_feedback_for_redesign_loop(self):
        project = build_mvp_robot_arm_project()
        evaluation_run = project["evaluation_run"]

        # the MVP now evaluates with REAL MuJoCo physics (not the synthetic mock), and the STRESS tier surfaces
        # genuine failures (objects past the reliable grasp envelope + heavy) for the redesign loop to act on.
        self.assertEqual("mujoco", evaluation_run.backend)
        self.assertGreaterEqual(len(evaluation_run.failures), 1)
        self.assertTrue(evaluation_run.failures[0].regression_scene_id)
        self.assertTrue(evaluation_run.failures[0].suggested_fixes)        # a real, specific fix (not a stub)
        self.assertIn(evaluation_run.failures[0].failure_type,
                      {"missed_grasp", "wrong_bin", "dropped", "instability", "unknown"})
        regression_scene = project["regression_scene_set"].scenes[0]
        self.assertIn("regression_from_evaluation", regression_scene.requirement_trace)
        # regression scenes are now FAILURE-CONDITIONED (plan §31.5): a targeted one-variable counterfactual
        # keyed on the failure type, not a generic 'bin_spacing: wider' stamp on every scene.
        vp = regression_scene.variation_parameters
        self.assertEqual(evaluation_run.failures[0].failure_type, vp["failure_type"])
        self.assertIn("counterfactual", vp)
        self.assertIn("changed_variable", vp)

